import { verdicts } from "../core/summary";
import type { Finding, RecordRow, Report } from "../core/types";
import { message, uiText, verdictText, type Lang, type MessageContext } from "../i18n";
import { buildControls, confidenceOf, hasGap, needsAction, scoreOf, severityOf, TEXT as CTEXT, type Control } from "./controls";
import { evidenceFor, expectedFor } from "./observed";
import { ATTACK_NOTICE, riskOf } from "./attack";

/**
 * The report as Markdown, to paste into a ticket, an email or an AI assistant.
 * Same structure as the screen: action plan, then one control per topic with its
 * evidence (records as collected, and whether both resolvers agree), its checks
 * and the action it needs. Nothing is added that the screen does not show; the
 * raw HTTP responses stay in the JSON.
 */

const TEXT = {
  es: {
    intro:
      "Informe generado por Domain Auditor con consultas en vivo a resolvedores DNS públicos (DNS sobre HTTPS), RDAP y RIPEstat. Los datos son reales; la valoración es automática y no conoce el contexto del dominio.",
    identity: "Quién es",
    summary: "Resumen",
    compare: "Contraste entre resolvedores",
    compareSame: "iguales",
    compareDiffer: "DISTINTOS",
    context: "Depende del contexto",
    source: "Informe en vivo",
  },
  en: {
    intro:
      "Report generated by Domain Auditor from live queries to public DNS resolvers (DNS over HTTPS), RDAP and RIPEstat. The data is real; the assessment is automatic and does not know the domain's context.",
    identity: "Who it is",
    summary: "Summary",
    compare: "Resolver cross-check",
    compareSame: "same",
    compareDiffer: "DIFFERENT",
    context: "Depends on context",
    source: "Live report",
  },
};

const zone = (rows: RecordRow[]) => rows.map((r) => `${r.name}  ${r.ttl !== undefined ? `${r.ttl}  ` : ""}${r.type}  ${r.data}`).join("\n");
const block = (text: string) => "```\n" + text + "\n```";
const isProblem = (f: Finding) => f.status === "fail" || f.status === "warn";

/** One control: state, evidence as collected, the checks and, if needed, the action. */
function controlMd(c: Control, report: Report, lang: Lang, ctx: MessageContext): string {
  const t = uiText(lang);
  const x = TEXT[lang];
  const k = CTEXT[lang];
  const domain = report.query;
  const tags = [k.states[c.state], needsAction(c) ? k.severity[severityOf(c)] : "", k.confidence[confidenceOf(c)]].filter(Boolean).join(" · ");
  const out = [`### ${k.controls[c.id] ?? c.id}: ${tags}`];

  if (c.evidence) {
    const ev = evidenceFor(c.evidence, c.findings[0]!.section, domain);
    const consensus = c.check ? (c.check.same ? k.agree : k.differ) : "";
    out.push(`**${k.evidence}** (\`${ev.where}\`${consensus ? `, ${consensus}` : ""}):`, block(ev.rows.length ? zone(ev.rows) : c.findings.some(({ f }) => f.id === "ct.unavailable") ? k.ctFailed : k.empty));
    if (c.check && !c.check.same) out.push(c.check.providers.map((p, i) => `- ${p}: ${c.check!.answers[i]!.join(" | ") || "—"}`).join("\n"));
  }

  out.push(
    `**${k.checks}:**`,
    c.findings
      .map(({ f }) => {
        const m = message(lang, f.id, f.params, ctx);
        const lines = [`- [${t.status[f.status]}] ${m.title}${m.detail ? ` — \`${m.detail.replace(/`/g, "")}\`` : ""}`];
        if (isProblem(f) && m.what) lines.push(`  ${m.what}`);
        if (m.context) lines.push(`  ${x.context}: ${m.context}`);
        return lines.join("\n");
      })
      .join("\n"),
  );

  const risk = c.state === "na" ? null : riskOf(c.id, !hasGap(c), lang);
  if (risk) {
    out.push(
      `**${hasGap(c) ? k.risk : k.prevents}:** ${risk.text}`,
      ...(risk.techniques.length ? [`${k.related} ${risk.techniques.map((t) => `${t.id} ${t.name} (${t.tactic})`).join("; ")}`] : []),
    );
  }

  const problems = c.findings.map(({ f }) => f).filter(isProblem);
  const withFix = (problems.length ? problems : c.findings.map(({ f }) => f)).filter((f) => f.suggest?.length || f.files?.length || isProblem(f));
  if (withFix.length) {
    const action: string[] = [];
    const seen = new Set<string>();
    for (const f of withFix) {
      const m = message(lang, f.id, f.params, ctx);
      const steps = (m.steps ?? []).filter((st) => !seen.has(st) && (seen.add(st), true));
      if (isProblem(f) && steps.length) action.push(steps.map((s, i) => `${i + 1}. ${s}`).join("\n"));
      if (f.suggest?.length) action.push(block(f.suggest.map((s) => `${s.name} ${s.type} ${s.value}`).join("\n")));
      for (const file of f.files ?? []) action.push(file.url, block(file.content.replace(/\r\n/g, "\n").trimEnd()));
    }
    const hasRecord = withFix.some((f) => f.suggest?.length || f.files?.length);
    if (!hasRecord && c.evidence) action.push(`${k.expected} ${expectedFor(c.evidence, domain, lang)}`);
    out.push(`**${k.action}${c.state === "optional" ? ` (${k.states.optional.toLowerCase()})` : ""}:**`, ...action);
  }
  return out.join("\n\n");
}

export function reportMarkdown(report: Report, lang: Lang, identity: Array<[string, string]>, ctx: MessageContext, url: string): string {
  const t = uiText(lang);
  const x = TEXT[lang];
  const k = CTEXT[lang];
  const groups = buildControls(report);
  const controls = groups.flatMap((g) => g.controls);
  const out: string[] = [
    `# Domain Auditor · ${report.query}`,
    `${t.generated}: ${report.generatedAt} · ${x.source}: ${url}`,
    `> ${x.intro}`,
  ];

  if (identity.length) out.push(`## ${x.identity}`, identity.map(([key, v]) => `- **${key}:** ${v}`).join("\n"));

  const list = verdicts(report);
  if (list.length) {
    out.push(
      `## ${x.summary}`,
      list
        .map((v) => {
          const vt = verdictText(lang, v);
          return `- **${vt.title}: ${t.levels[v.level]}.** ${vt.text}`;
        })
        .join("\n"),
    );
  }

  const score = scoreOf(report, groups);
  const rank = ["high", "medium", "low"];
  const actions = controls
    .filter(needsAction)
    .sort((a, b) => rank.indexOf(severityOf(a)) - rank.indexOf(severityOf(b)) || (a.state === b.state ? 0 : a.state === "fail" ? -1 : 1));
  out.push(
    `## ${k.plan}`,
    [
      `${k.metricControls}: ${score.total ? k.metricControlsValue.replace("{ok}", String(score.passed)).replace("{total}", String(score.total)) : k.metricNotEvaluable}`,
      score.unverified ? k.metricUnverified.replace("{n}", String(score.unverified)) : "",
      score.notApplicable ? k.metricNa.replace("{n}", String(score.notApplicable)) : "",
      score.extrasTotal ? k.metricExtras.replace("{n}", String(score.extras)).replace("{total}", String(score.extrasTotal)) : "",
    ]
      .filter(Boolean)
      .join(" · ") + ".",
    actions.length
      ? actions.map((c, i) => `${i + 1}. **${k.controls[c.id] ?? c.id}** (${k.states[c.state]}, ${k.severity[severityOf(c)].toLowerCase()}): ${message(lang, c.findings[0]!.f.id, c.findings[0]!.f.params, ctx).title}`).join("\n")
      : k.planNone,
  );

  for (const g of groups) {
    out.push(`## ${k.groups[g.id]}`);
    for (const c of g.controls) out.push(controlMd(c, report, lang, ctx));
  }

  if (report.resolverCheck?.length) {
    out.push(
      `## ${x.compare}`,
      report.resolverCheck.map((c) => `- ${c.name} ${c.type}: ${c.same ? x.compareSame : x.compareDiffer}`).join("\n"),
    );
  }
  out.push(`> ${ATTACK_NOTICE}`);
  // In text, the mailbox the user types on screen is shown as a visible slot.
  return out.join("\n\n").replaceAll("{mailbox}", lang === "es" ? "<buzón>" : "<mailbox>") + "\n";
}
