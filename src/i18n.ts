export const MESSAGES: Record<Lang, Messages> = { es, en };

export function uiText(lang: Lang): UiText {
  return ui[lang];
}

function fill(template: string, params: Params = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}

const PANEL_TEXT: Record<Lang, { known: string; unknown: string }> = {
  es: {
    known: "Entra en el panel de DNS de {provider}, donde está gestionado el dominio.",
    unknown: "Entra en el panel donde se gestiona el DNS del dominio (lo indican sus servidores NS: suele ser el registrador o el hosting).",
  },
  en: {
    known: "Sign in to {provider}'s DNS panel, where the domain is managed.",
    unknown: "Sign in to the panel where the domain's DNS is managed (its NS servers tell which: usually the registrar or the hosting).",
  },
};

export interface MessageContext {
  /** DNS provider detected from the NS records, if any. */
  dnsProvider?: string;
}

export function message(lang: Lang, id: string, params?: Params, ctx: MessageContext = {}): Message {
  const msg: Message = MESSAGES[lang][id] ?? { title: id };
  const panel = ctx.dnsProvider ? PANEL_TEXT[lang].known.replace("{provider}", ctx.dnsProvider) : PANEL_TEXT[lang].unknown;
  const p: Params = { ...params, panel };
  if (typeof p.range === "string") p.range = RANGES[lang][p.range] ?? p.range;
  if (typeof p.date === "string" && /^\d{4}-\d{2}-\d{2}$/.test(p.date)) {
    p.date = new Date(`${p.date}T00:00:00Z`).toLocaleDateString(lang === "es" ? "es-ES" : "en-GB", { timeZone: "UTC" });
  }
  return {
    title: fill(msg.title, p),
    detail: msg.detail ? fill(msg.detail, p) : undefined,
    what: msg.what ? fill(msg.what, p) : undefined,
    steps: msg.steps?.map((step) => fill(step, p)),
    tech: msg.tech ? fill(msg.tech, p) : undefined,
    context: msg.context ? fill(msg.context, p) : undefined,
  };
}

const VERDICTS = { es: verdictsEs, en: verdictsEn };

export function verdictText(lang: Lang, v: Verdict): { title: string; text: string } {
  return VERDICTS[lang][`${v.area}.${v.reason}`] ?? { title: v.area, text: v.reason };
}

export function detectLang(): Lang {
  const param = new URLSearchParams(location.search).get("lang");
  if (param === "es" || param === "en") return param;
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "es" || saved === "en") return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
}
